/** Get prompts belonging to a given category. */
export function getPromptsByCategory(categoryKey: string): PromptDef[] {
  return PROMPT_DEFS.filter((p) => {
    // Keys starting with category prefix belong to that category
    if (categoryKey === "main" && p.key === "main") return true;
    if (categoryKey === "file_parser" && p.key === "file_parser") return true;
    if (categoryKey === "decomposer" && p.key.startsWith("decomposer_")) return true;
    if (categoryKey === "skills" && ["evaluator", "grill_me", "plan_expert_judgment", "plan_step_breakdown", "plan_analogy", "plan_pert"].includes(p.key)) return true;
    return false;
  });
}

/** Get the default content for a prompt key, or empty string if not found. */
export function getDefaultPrompt(key: string): string {
  const def = PROMPT_DEFS.find((p) => p.key === key);
  return def?.defaultContent ?? "";
}

/** All valid prompt keys. */
export const PROMPT_KEYS = PROMPT_DEFS.map((p) => p.key);

/**
 * Resolve a prompt value from session overrides or fall back to defaults.
 * Returns `overrides[key]` if non-empty, otherwise `getDefaultPrompt(key)`.
 */
export function resolvePrompt(
  key: string,
  overrides?: Record<string, string>,
): string {
  if (overrides?.[key]?.trim()) return overrides[key];
  return getDefaultPrompt(key);
}
